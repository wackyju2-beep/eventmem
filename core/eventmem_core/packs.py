"""eventmem_core.packs — one folder is one decision backend.

A *pack* is a directory with a ``config.yaml`` in it; the directory name is the backend's
name.  Dropping a folder into ``<hermes_home>/eventmem/backends/`` is the whole install
step — there is no registry, no global list, and nothing to unregister.

Three shapes, decided by which keys are present::

    weights: model.gguf          -> "self"      eventmem may launch it (daemon-managed)
    base_url: …  external: true  -> "external"  someone else runs it (LM Studio, systemd)
    base_url: …                  -> "remote"    a hosted endpoint

``config.yaml`` is hand-written as often as it is generated by the GUI, so loading is
lenient in the same way :func:`eventmem_core.settings.apply` is: an unknown key or a bad
number is reported through ``warn`` and dropped, never fatal.  Only a pack that cannot
possibly work (no source, no protocol, both sources at once) raises :class:`PackError`.

The file is read with PyYAML when available.  It is not a dependency of the plugin — only
the daemon reads packs — so the import stays local and the failure says what to install.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Mapping, Optional

from .providers import PROTOCOLS

__all__ = ["PACK_FILE", "KINDS", "Pack", "PackError", "load_pack", "discover",
           "parse_text", "save_text"]

#: The only file a pack needs.
PACK_FILE = "config.yaml"

#: ``self`` = we may launch it; ``external`` = already running elsewhere; ``remote`` = hosted.
KINDS = ("self", "external", "remote")

_KNOWN_KEYS = frozenset({
    "protocol", "model", "weights", "base_url", "external", "launch", "args", "port",
    "api_key_env", "api_key", "margin", "license", "note", "check_model",
    "release_after_pass",
})


class PackError(ValueError):
    """This folder cannot be a backend (missing source, bad protocol, …)."""


@dataclass(frozen=True)
class Pack:
    """One resolved backend.  Frozen: settings are replaced, never tuned in place."""

    name: str
    path: str
    protocol: str
    kind: str
    model: str = ""
    weights: str = ""
    base_url: str = ""
    launch: str = ""
    args: tuple[str, ...] = ()
    port: int = 0
    api_key_env: str = ""
    api_key: str = ""
    margin: Optional[float] = None
    license: str = ""
    note: str = ""
    #: Ask ``/v1/models`` whether ``model`` exists before trusting this backend. LM Studio
    #: with JIT lists every model, loaded or not, so this catches a renamed weight up front
    #: instead of stalling every round on a model id the server does not know.
    check_model: bool = False
    #: A ``self`` pack may hold the GPU hostage between passes.  With this on, the daemon
    #: stops it again as soon as the pass that started it ends (weights back out of VRAM).
    release_after_pass: bool = False

    @property
    def needs_key(self) -> bool:
        """True when we have a hosted endpoint but no key configured anywhere."""
        return self.kind == "remote" and bool(self.base_url) and not self.key()

    def key(self) -> str:
        """The API key: environment first (never written by the GUI), then the file."""
        if self.api_key_env:
            value = os.environ.get(self.api_key_env, "")
            if value:
                return value
        return self.api_key

    def describe(self) -> dict[str, Any]:
        """Plain snapshot for logs / ``--print-settings``.  Never includes the key itself."""
        return {
            "name": self.name,
            "path": self.path,
            "protocol": self.protocol,
            "kind": self.kind,
            "model": self.model,
            "weights": self.weights,
            "base_url": self.base_url,
            "launch": self.launch,
            "args": list(self.args),
            "port": self.port,
            "api_key_env": self.api_key_env,
            "has_key": bool(self.key()),
            "margin": self.margin,
            "license": self.license,
            "check_model": self.check_model,
            "release_after_pass": self.release_after_pass,
        }


# --------------------------------------------------------------------------- mapping → Pack

def _warn(warn: Optional[Callable[[str], None]], message: str) -> None:
    if warn is not None:
        warn(message)


def _int(value: Any, default: int) -> int:
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return default


def _float01(value: Any) -> Optional[float]:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if 0.0 <= number <= 1.0 else None


def _args(value: Any) -> tuple[str, ...]:
    if isinstance(value, str):
        return tuple(part for part in value.split() if part)
    try:
        return tuple(str(part) for part in value)
    except TypeError:
        return ()


def from_mapping(
    name: str,
    directory: str | os.PathLike,
    mapping: Mapping[str, Any],
    *,
    warn: Optional[Callable[[str], None]] = None,
) -> Pack:
    """Build a :class:`Pack` from an already-parsed ``config.yaml``."""
    if not isinstance(mapping, Mapping):
        raise PackError(f"{name}: config.yaml must be a mapping")

    unknown = sorted(set(mapping) - _KNOWN_KEYS)
    for key in unknown:
        _warn(warn, f"{name}: 未知配置项 {key}（已忽略）")

    protocol = str(mapping.get("protocol") or "").strip()
    if protocol not in PROTOCOLS:
        raise PackError(
            f"{name}: protocol={protocol!r} 不认识；可用 {', '.join(PROTOCOLS)}"
        )

    base_url = str(mapping.get("base_url") or "").strip().rstrip("/")
    weights = str(mapping.get("weights") or "").strip()
    launch = str(mapping.get("launch") or "").strip()
    if base_url and (weights or launch):
        raise PackError(f"{name}: base_url 与 weights/launch 不能同时写（本地 or 远端）")
    if not base_url and not weights and not launch:
        raise PackError(f"{name}: 至少写 weights / launch（本地）或 base_url（已装好的服务 / 云端）")

    external = bool(mapping.get("external"))
    if weights or launch:
        kind = "self"
    elif external:
        kind = "external"
    else:
        kind = "remote"
    if external and not base_url:
        raise PackError(f"{name}: external: true 需要同时写 base_url")

    model = str(mapping.get("model") or "").strip()
    if not model:
        if weights:
            model = Path(weights).stem
        else:
            raise PackError(f"{name}: 远端 / 外部后端必须写 model（服务的模型 id）")

    directory = Path(directory)
    if weights:
        candidate = Path(weights)
        weights = str(candidate if candidate.is_absolute() else (directory / candidate))

    if kind != "self" and launch:
        raise PackError(f"{name}: 只有本地 pack 能写 launch（{kind} 不归我们启动）")
    if kind == "self" and not launch:
        launch = "auto"

    margin = None
    if "margin" in mapping:
        margin = _float01(mapping.get("margin"))
        if margin is None:
            _warn(warn, f"{name}: margin={mapping.get('margin')!r} 不在 0–1；已忽略")

    port = 0
    if "port" in mapping:
        parsed = _int(mapping.get("port"), -1)
        if 0 <= parsed <= 65535:
            port = parsed
        else:
            _warn(warn, f"{name}: port={mapping.get('port')!r} 不合法；改为自动分配")

    check_model = bool(mapping.get("check_model"))
    if check_model and kind != "self" and not base_url:
        check_model = False
    if check_model and kind == "self":
        _warn(warn, f"{name}: check_model 只对远端 / 外部服务有意义；已忽略")
        check_model = False

    return Pack(
        name=str(name),
        path=str(directory),
        protocol=protocol,
        kind=kind,
        model=model,
        weights=weights,
        base_url=base_url,
        launch=launch,
        args=_args(mapping.get("args")),
        port=port,
        api_key_env=str(mapping.get("api_key_env") or ""),
        api_key=str(mapping.get("api_key") or ""),
        margin=margin,
        license=str(mapping.get("license") or ""),
        note=str(mapping.get("note") or ""),
        check_model=check_model,
        release_after_pass=bool(mapping.get("release_after_pass")),
    )


# --------------------------------------------------------------------------- file → Pack

def _read_mapping(path: Path) -> Mapping[str, Any]:
    try:
        import yaml  # noqa: PLC0415 - only the daemon reads packs; the plugin never does
    except Exception as exc:  # noqa: BLE001
        raise PackError("读取 config.yaml 需要 PyYAML（pip install pyyaml）") from exc
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise PackError(f"读不到 {path}（{exc}）") from exc
    try:
        data = yaml.safe_load(text)
    except Exception as exc:  # noqa: BLE001
        raise PackError(f"{path} 不是合法 YAML（{exc}）") from exc
    if data is None:
        raise PackError(f"{path} 是空的")
    if not isinstance(data, Mapping):
        raise PackError(f"{path} 顶层必须是一个映射")
    return data


def load_pack(
    path: str | os.PathLike,
    *,
    mapping: Optional[Mapping[str, Any]] = None,
    warn: Optional[Callable[[str], None]] = None,
) -> Pack:
    """Load one pack directory (or ``…/config.yaml`` itself).

    *mapping* skips the file read — tests and the GUI's "preview" path use it.
    """
    directory = Path(path).expanduser()
    if directory.name == PACK_FILE:
        directory = directory.parent
    if not directory.is_dir():
        raise PackError(f"{directory} 不是一个目录")
    config = directory / PACK_FILE
    if mapping is None:
        if not config.exists():
            raise PackError(f"{directory} 里没有 {PACK_FILE}")
        mapping = _read_mapping(config)
    pack = from_mapping(directory.name, directory, mapping, warn=warn)
    if pack.weights and not Path(pack.weights).exists():
        _warn(warn, f"{pack.name}: 权重文件不存在 {pack.weights}")
    return pack


def discover(
    root: str | os.PathLike,
    *,
    warn: Optional[Callable[[str], None]] = None,
) -> tuple[list[Pack], list[str]]:
    """Every pack under *root*, plus the problems found on the way.

    A broken pack must not hide the good ones: it is reported and skipped.  Directories
    without a ``config.yaml`` are not packs at all (no message).
    """
    root = Path(root).expanduser()
    packs: list[Pack] = []
    problems: list[str] = []
    if not root.is_dir():
        return packs, problems

    def collect(message: str) -> None:
        problems.append(message)
        _warn(warn, message)

    for child in sorted(root.iterdir(), key=lambda p: p.name):
        if not child.is_dir() or child.name.startswith((".", "_")):
            continue
        if not (child / PACK_FILE).exists():
            continue
        try:
            packs.append(load_pack(child, warn=collect))
        except PackError as exc:
            collect(str(exc))
    return packs, problems


# --------------------------------------------------------------------------- writing

def parse_text(name: str, directory: str | os.PathLike, text: str, *,
               warn: Optional[Callable[[str], None]] = None) -> Pack:
    """Validate a ``config.yaml`` the GUI is about to save.

    Raises :class:`PackError` with a sentence a human can act on; on success returns the
    parsed pack so the caller can show what it means (kind, resolved weights path, …).
    """
    try:
        import yaml  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        raise PackError("写 config.yaml 需要 PyYAML（pip install pyyaml）") from exc
    try:
        data = yaml.safe_load(text)
    except Exception as exc:  # noqa: BLE001
        raise PackError(f"不是合法 YAML：{exc}") from exc
    if data is None:
        raise PackError("config.yaml 是空的")
    if not isinstance(data, Mapping):
        raise PackError("顶层必须是一个映射（每行 key: value）")
    return from_mapping(str(name), Path(str(directory)).expanduser(), data, warn=warn)


def save_text(directory: str | os.PathLike, text: str, *, create_only: bool = False) -> Path:
    """Write ``config.yaml`` byte-for-byte (comments and all), atomically.

    The GUI edits the file itself, not a model of it: whatever the user saw in the textarea
    is what lands on disk, so hand-written comments survive a round-trip through the UI.
    """
    folder = Path(directory).expanduser()
    target = folder / PACK_FILE
    if create_only and target.exists():
        raise PackError(f"{folder.name} 已经有 {PACK_FILE}；改它而不是新建")
    folder.mkdir(parents=True, exist_ok=True)
    temp = folder / (PACK_FILE + ".tmp")
    temp.write_text(text.rstrip() + "\n", encoding="utf-8")
    os.replace(temp, target)
    return target
